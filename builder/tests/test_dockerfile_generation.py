def test_dockerfile_generation_without_neurodocker_dependency() -> None:
    config = default_config()
    compiled = compile_recipe(
        resolve_recipe(config, "dcm2niix"),
        architecture="x86_64",
        include_dirs=config.include_dirs,
    )
    dockerfile = render_dockerfile(compiled.definition)
    assert dockerfile.startswith("# Generated by Neurodocker and Reproenv.")
    assert "FROM ubuntu:20.04" in dockerfile
    assert "from=neurocontainer-cache" in dockerfile
    assert "dcm2niix_lnx.zip" in dockerfile
    assert "DEPLOY_PATH" in dockerfile
    assert "# Save specification to JSON." in dockerfile


def _foreign_copy_recipe(tmp_path: Path, copy_options: dict) -> Path:
    recipe_dir = tmp_path / "foreign-source"
    recipe_dir.mkdir()
    (recipe_dir / "build.yaml").write_text(
        yaml.safe_dump(
            {
                "name": "foreign-source",
                "version": "1.0.0",
                "readme": "Foreign source fixture",
                "architectures": ["aarch64"],
                "categories": ["programming"],
                "variables": {"vendor": "example.org/vendor:1.2.3"},
                "build": {
                    "kind": "neurodocker",
                    "base-image": "ubuntu:22.04",
                    "pkg-manager": "apt",
                    "directives": [
                        {"copy": ["/app/src", "/opt/src"], **copy_options},
                        {"copy": ["/app/Makefile", "/opt/Makefile"], **copy_options},
                    ],
                },
            }
        )
    )
    return recipe_dir


def test_copy_from_foreign_image_uses_explicit_platform_without_local_staging(
    tmp_path: Path,
) -> None:
    recipe_dir = _foreign_copy_recipe(
        tmp_path,
        {
            "from_image": "{{ context.vendor }}",
            "from_platform": "linux/amd64",
        },
    )
    compiled = compile_recipe(recipe_dir, architecture="aarch64")
    dockerfile = render_dockerfile(compiled.definition)
    stage = "FROM --platform=linux/amd64 example.org/vendor:1.2.3 AS copy-source-0"
    assert dockerfile.count(stage) == 1
    assert dockerfile.index(stage) < dockerfile.index("FROM ubuntu:22.04")
    assert 'COPY --from=copy-source-0 ["/app/src",' in dockerfile
    assert 'COPY --from=copy-source-0 ["/app/Makefile",' in dockerfile


@pytest.mark.parametrize(
    "options, message",
    [
        ({"from_platform": "linux/amd64"}, "requires from_image"),
        ({"from_image": "vendor\nFROM evil"}, "must be an image reference"),
        (
            {"from_image": "vendor", "from_platform": "linux/arm64 --evil"},
            "must be an OCI platform",
        ),
    ],
)
def test_copy_rejects_invalid_image_options(tmp_path: Path, options, message) -> None:
    recipe_dir = _foreign_copy_recipe(tmp_path, options)
    with pytest.raises(ValueError, match=message):
        compile_recipe(recipe_dir, architecture="aarch64")


def test_compile_rejects_nested_test_directive(tmp_path: Path) -> None:
    recipe_dir = _foreign_copy_recipe(tmp_path, {})
    recipe = yaml.safe_load((recipe_dir / "build.yaml").read_text())
    recipe["build"]["directives"] = [
        {"test": {"name": "smoke", "builtin": "test_deploy.sh"}}
    ]
    (recipe_dir / "build.yaml").write_text(yaml.safe_dump(recipe))
    with pytest.raises(ValueError, match="fulltest.yaml"):
        compile_recipe(recipe_dir, architecture="aarch64")


@pytest.mark.parametrize("pkg_manager", ["apt", "yum", ""])
@pytest.mark.parametrize("shell", ["sh", "bash"])
def test_bootstrap_startup_script_execs_command_and_receives_sigterm(
    tmp_path: Path, pkg_manager: str, shell: str
) -> None:
    snippet = _default_template_command(pkg_manager)
    block = re.search(
        r'if \[ ! -f "\$ND_ENTRYPOINT" \]; then\n(.*?)\nfi', snippet, re.S
    )
    assert block is not None, snippet
    startup = tmp_path / "startup.sh"
    subprocess.run(
        ["sh", "-e", "-c", f'ND_ENTRYPOINT="$1"\n{block.group(0)}', "_", str(startup)],
        check=True,
    )
    startup.chmod(0o755)
    assert 'exec "$@"' in startup.read_text()
    assert "exec /usr/bin/env bash" in startup.read_text()

    ready = tmp_path / "ready"
    got_sig = tmp_path / "sig"
    child = tmp_path / "child.py"
    child.write_text(
        "import os, signal, sys, time\n"
        "ready, got_sig = sys.argv[1], sys.argv[2]\n"
        "def h(signum, _):\n"
        "    open(got_sig, 'w').write(str(signum))\n"
        "    raise SystemExit(128 + signum)\n"
        "signal.signal(signal.SIGTERM, h)\n"
        "open(ready, 'w').write(str(os.getpid()))\n"
        "time.sleep(10)\n"
    )
    proc = subprocess.Popen(
        [shell, str(startup), sys.executable, str(child), str(ready), str(got_sig)],
        env={**os.environ, "USER": "tester"},
    )
    deadline = time.time() + 5.0
    while not ready.exists() and time.time() < deadline:
        time.sleep(0.02)
    assert ready.exists(), "child did not start"
    assert int(ready.read_text().strip()) == proc.pid
    proc.send_signal(signal.SIGTERM)
    rc = proc.wait(timeout=5)
    assert rc == 128 + signal.SIGTERM.value
    assert got_sig.read_text().strip() == str(signal.SIGTERM.value)
